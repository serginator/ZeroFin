#!/bin/sh
# Makes the six demo posters (64x96 baseline JPEG) and writes src/jellyfin/demo_posters.inc.
# Needs ffmpeg and xxd. Run it from anywhere. The .inc file is committed, so a normal build needs neither.
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
out="$root/src/jellyfin/demo_posters.inc"
colors="c0=0x1d3b52:c1=0x00a4dc c0=0x52201d:c1=0xdc6a00 c0=0x1d522b:c1=0x7cdc00 c0=0x3a1d52:c1=0xd400dc c0=0x52481d:c1=0xdcc800 c0=0x1d4a52:c1=0x00dcb4"
n=0
{
  echo "// Generated by tools/gen-demo-posters.sh. Do not edit."
  for c in $colors; do
    ffmpeg -hide_banner -loglevel error -y -f lavfi -i "gradients=s=64x96:${c}:nb_colors=2:seed=$((n + 3)):speed=0.01" \
      -frames:v 1 -q:v 5 -pix_fmt yuvj420p -f mjpeg "$tmp/p$n.jpg"
    file "$tmp/p$n.jpg" | grep -q "baseline" || { echo "poster $n is not baseline" >&2; exit 1; }
    echo "static const unsigned char kDemoPoster$n[] = {"
    xxd -i < "$tmp/p$n.jpg"
    echo "};"
    n=$((n + 1))
  done
  echo "static const struct { const unsigned char* data; unsigned size; } kDemoPosters[] = {"
  i=0
  while [ $i -lt $n ]; do echo "    {kDemoPoster$i, sizeof(kDemoPoster$i)},"; i=$((i + 1)); done
  echo "};"
} > "$out"
echo "wrote $out"
